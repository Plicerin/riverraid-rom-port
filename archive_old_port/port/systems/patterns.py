# Number of rows per pattern (JTZ: all patterns are 28 rows max)
PATTERN_ROW_COUNT = 28


def get_pattern(pattern_id: int) -> list[int]:
    """Return the byte rows for the given pattern ID (0–14)."""
    if 0 <= pattern_id <= 14:
        return ALL_PATTERNS[pattern_id]
    raise ValueError(f"Invalid pattern ID: {pattern_id} (expected 0-14)")


def get_row(pattern_id: int, row_index: int) -> int:
    """Return a single row byte from the given pattern.

    Args:
        pattern_id: Pattern ID (0–14).
        row_index: Row within the pattern (0–27).

    Returns:
        8-bit row byte.
    """
    pattern = get_pattern(pattern_id)
    return pattern[row_index % len(pattern)]
