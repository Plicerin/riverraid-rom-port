// Generates riverraidPlayfieldData.mjs from the River Raid ROM: the playfield
// pattern bytes the kernel reads through (PF1Ptr),Y / (PF2Ptr),Y, plus the
// tables used by the block generator. Addresses are from the river-raid-wiz
// symbol list; the PF ranges were measured with tools/atari/pf-reads.mjs
// (60,000 frames, levels 1..48 read only $FC00-$FCBC and $FD00-$FDA1).
//
// Usage: node tools/gen-playfield.mjs [path/to/River Raid.a26]

import { writeFileSync } from 'node:fs';
import { loadRom } from './atari/vcs.mjs';

const rom = loadRom(process.argv[2]);
const bytes = (addr, length) => Array.from(rom.subarray(addr - 0xf000, addr - 0xf000 + length));
const hex = (v) => `0x${v.toString(16).toUpperCase().padStart(2, '0')}`;
const list = (arr) => `[${arr.map(hex).join(', ')}]`;
const wrapped = (arr) => {
  const rows = [];
  for (let i = 0; i < arr.length; i += 16) rows.push(`    ${arr.slice(i, i + 16).map(hex).join(', ')},`);
  return `[\n${rows.join('\n')}\n  ]`;
};

const tables = {
  BANK_PTR_TAB: [0xfcf1, 15, 'low pointers of PFPat0..PFPat14'],
  PAGE_FLAG_TAB: [0xfbb7, 4, 'page flags for island blocks'],
  SHAPE_POS_TAB: [0xfbc6, 15, 'house x-position by PF1 pattern id'],
  ENEMY_ID_TAB: [0xffc0, 8, 'random enemy ids'],
  ROAD_COLOR_TAB: [0xffb3, 13, 'road colors for block lines 0..ROAD_HEIGHT-1 (shares bytes with VolumeTab)'],
  INIT_TAB: [0xfdb1, 39, 'GameInit values for PF1Lst..colorPtr'],
  COLOR_TAB: [0xfff7, 6, 'ColorTab: PFcolor..zero1 and NUSIZ1..CTRLPF at frame start (last byte is <START)'],
  ANIMATE_ID_TAB: [0xfbf9, 11, 'next shape id for animated objects'],
  SCORE_TAB: [0xfe53, 11, 'score per shape id (DIGIT_H multiples, bit 7 = hundreds)'],
  VOLUME_TAB: [0xffbe, 4, 'jet sound volume by up/down (shares bytes with EnemyIdTab)'],
  JET_PAGE_TAIL: [0xfcbc, 0x36, 'page $FC bytes from JetStraight; shapePtr0 = <JetX-1 indexes from here'],
  DIGITS: [0xfb00, 0x59, 'score/lives digit graphics Zero..Space and the first Copyright byte'],
};

const out = [
  '// GENERATED by tools/gen-playfield.mjs from the River Raid ROM - do not edit.',
  '',
  '// Playfield pattern bytes, by page ($FC/$FD). Index with the low byte of the pointer.',
  `export const PF_PAGE_FC = ${wrapped(bytes(0xfc00, 0xbd))};`,
  `export const PF_PAGE_FD = ${wrapped(bytes(0xfd00, 0xa2))};`,
  '',
  ...Object.entries(tables).map(([name, [addr, len, note]]) => `// ${note} ($${addr.toString(16).toUpperCase()})\nexport const ${name} = ${list(bytes(addr, len))};`),
  '',
];
writeFileSync('riverraidPlayfieldData.mjs', out.join('\n'));
console.log('wrote riverraidPlayfieldData.mjs');
