// Generates riverraidKernelSprites.mjs from the River Raid ROM.
//
// The kernel draws each object from two pointers, shapePtr1a/shapePtr1b, on
// alternating scanlines ("the data is displayed interlaced, this gives in a
// single line resolution"). It is a two-line kernel repeated twelve times per
// block, indexing (ptr),Y with ptr = label-1 and Y = 12..1, so each object is
// 12 bytes from each table, read past the end of the label into the next
// table, exactly as the ROM does. Per pair, the B line is drawn above the A line.
//
// Usage: node tools/gen-kernel-sprites.mjs [path/to/River Raid.a26]

import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const ROM_PATH = process.argv[2] ?? 'reference/river-raid-wiz-main/baserom.a26';
const EXPECTED_MD5 = '393948436d1f4cc3192410bb918f9724';
const SHAPE_PTR_1A_TAB = 0xFFC8; // shapePtr1aTab (Jentzsch line 3599)
const SHAPE_PTR_1B_TAB = 0xFBBB; // shapePtr1bTab (Jentzsch line 2568)
const SHAPE_PAGE = 0xFE00;       // all object shapes live in page $FE
const NUM_SHAPES = 11;           // ID_EXPLOSION0 .. ID_FUEL
const KERNEL_PAIRS = 12;

const rom = readFileSync(ROM_PATH);
const md5 = createHash('md5').update(rom).digest('hex');
if (md5 !== EXPECTED_MD5) throw new Error(`unexpected ROM md5 ${md5}`);

const byteAt = addr => rom[addr - 0xF000];
const hex = (n, w = 2) => n.toString(16).toUpperCase().padStart(w, '0');

const shapes = [];
for (let id = 0; id < NUM_SHAPES; id += 1) {
  const aAddr = SHAPE_PAGE | ((byteAt(SHAPE_PTR_1A_TAB + id) + 1) & 0xFF);
  const bAddr = SHAPE_PAGE | ((byteAt(SHAPE_PTR_1B_TAB + id) + 1) & 0xFF);
  const a = Array.from({ length: KERNEL_PAIRS }, (_, i) => byteAt(aAddr + i));
  const b = Array.from({ length: KERNEL_PAIRS }, (_, i) => byteAt(bAddr + i));
  shapes.push({ id, aAddr, bAddr, a, b });
}

const lines = [
  '// GENERATED by tools/gen-kernel-sprites.mjs from the River Raid ROM - do not edit.',
  '// Per shape id: 12 bytes read from shapePtr1a and shapePtr1b (page $FE), including',
  '// the bytes the kernel reads past each label. Bit 7 is the leftmost pixel.',
  'export const KERNEL_SHAPE_BYTES = [',
  ...shapes.map(s => `  { id: ${s.id}, aAddr: '$${hex(s.aAddr, 4)}', bAddr: '$${hex(s.bAddr, 4)}', a: [${s.a.map(v => `0x${hex(v)}`).join(', ')}], b: [${s.b.map(v => `0x${hex(v)}`).join(', ')}] },`),
  '];',
  '',
  '// Top-down scanline rows as the kernel displays them: for y = 11..0, B[y] then A[y].',
  'export function kernelShapeBitmap(shapeId) {',
  '  const shape = KERNEL_SHAPE_BYTES[shapeId];',
  '  if (!shape) return null;',
  '  const rows = [];',
  '  for (let y = shape.a.length - 1; y >= 0; y -= 1) {',
  '    rows.push(shape.b[y].toString(2).padStart(8, \'0\'));',
  '    rows.push(shape.a[y].toString(2).padStart(8, \'0\'));',
  '  }',
  '  return rows;',
  '}',
  '',
];
writeFileSync('riverraidKernelSprites.mjs', lines.join('\n'));
console.log(`wrote riverraidKernelSprites.mjs (${shapes.length} shapes)`);
